def visualize_deviations(data, name, mean_val):
    print(f"\n{name}:")
    print(f"  Среднее = {mean_val:.1f}")
    print("  Значения: ", end="")
    for val in data:
        diff = val - mean_val
        if diff > 0:
            print(f"[{val} +{diff:.0f}]", end=" ")
        elif diff < 0:
            print(f"[{val} {diff:.0f}]", end=" ")
        else:
            print(f"[{val} 0]", end=" ")
    print()


