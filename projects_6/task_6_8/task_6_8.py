print("""
╔═══════════════════════════════════════════════════════════════════════════════╗
║  ПОЧЕМУ ЕДИНИЦЫ ИЗМЕРЕНИЯ ДИСПЕРСИИ НЕУДОБНЫ ДЛЯ ИНТЕРПРЕТАЦИИ?               ║
╚═══════════════════════════════════════════════════════════════════════════════╝

ПРОБЛЕМА:
─────────
Дисперсия измеряется в КВАДРАТНЫХ единицах исходных данных.

Пример из нашего анализа:
  • Исходные данные: оценки студентов (баллы)
  • Дисперсия: баллы² (квадратные баллы)

Что это значит на практике?
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

Представьте, что мы измеряем рост людей в сантиметрах:
  • Средний рост: 170 см
  • Дисперсия: 64 см²

Что означает "64 квадратных сантиметра" в контексте роста человека?
  • Сложно представить физический смысл
  • Нельзя сказать "типичное отклонение от среднего составляет X см²"
  • Трудно интуитивно понять масштаб разброса

А если мы измеряем доход в рублях:
  • Средний доход: 50 000 руб.
  • Дисперсия: 250 000 000 руб²

"250 миллионов квадратных рублей" — что это значит? 
  • Эта цифра не имеет понятного экономического смысла
  • С ней трудно работать в уме
  • Она не помогает представить реальный разброс доходов

ПОЧЕМУ ТАК ПРОИСХОДИТ?
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

В процессе вычисления дисперсии мы:
  1. Находим отклонение (в исходных единицах)
  2. ВОЗВОДИМ ЕГО В КВАДРАТ (единицы измерения тоже возводятся в квадрат!)

Математически:
  • Если x измеряется в метрах, то (x - x̄)² измеряется в метрах²
  • Если x измеряется в секундах, то (x - x̄)² измеряется в секундах²
  • Если x измеряется в рублях, то (x - x̄)² измеряется в рублях²

Эти "квадратные единицы" неудобны для:
  • Визуализации разброса
  • Сравнения с исходными данными
  • Быстрой интерпретации результатов

Как решается эта проблема?
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

✅ РЕШЕНИЕ: СТАНДАРТНОЕ ОТКЛОНЕНИЕ (Standard Deviation)

Формула: σ = √(дисперсия)  или  s = √(s²)

Почему это решает проблему?
  • Квадратный корень "возвращает" единицы измерения в исходный вид
  • Теперь мы можем сказать: "Типичное отклонение от среднего составляет X единиц"
  • Легко интерпретировать и сравнивать с исходными данными

┌─────────────────────────────────────────────────────────────────────────────┐
│  ПРИМЕР ИЗ НАШИХ ДАННЫХ:                                                    │
├─────────────────────────────────────────────────────────────────────────────┤
│  Команда А:                                                                 │
│    • Дисперсия (s²) = {var_A:.2f} баллов²                                    │
│    • Стандартное отклонение (s) = {std_A:.2f} баллов                         │
│    • Интерпретация: "В типичном случае результат разработчика               │
│      отклоняется от среднего на {std_A:.2f} балла"                          │
│                                                                             │
│  Команда Б:                                                                 │
│    • Дисперсия (s²) = {var_B:.2f} баллов²                                    │
│    • Стандартное отклонение (s) = {std_B:.2f} баллов                         │
│    • Интерпретация: "В типичном случае результат разработчика               │
│      отклоняется от среднего на {std_B:.2f} балла"                          │
└─────────────────────────────────────────────────────────────────────────────┘
""".format(var_A=var_A, std_A=std_A, var_B=var_B, std_B=std_B))

