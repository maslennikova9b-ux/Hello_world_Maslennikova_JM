# Исходный набор данных
data = [4, 8, 6, 5, 3, 7, 9, 5]
print(f"\nИсходный набор данных: {data}")
print(f"Количество элементов: n = {len(data)}")

# ШАГ 1: Вычисляем среднее арифметическое
print("\n" + "-" * 50)
print("ШАГ 1: Вычисляем среднее арифметическое (x̄)")
print("-" * 50)

sum_data = sum(data)
n = len(data)
mean = sum_data / n

print(f"Сумма всех значений: {sum_data}")
print(f"Количество элементов: {n}")
print(f"Среднее = Сумма / n = {sum_data} / {n} = {mean:.2f}")

# ШАГ 2: Находим отклонения каждого значения от среднего
print("\n" + "-" * 50)
print("ШАГ 2: Находим отклонения (xi - x̄)")
print("-" * 50)

deviations = [x - mean for x in data]

print("Отклонения каждого значения:")
for i, (x, dev) in enumerate(zip(data, deviations)):
    print(f"  {x} - {mean:.2f} = {dev:.2f}")

print(f"\nСписок отклонений: {[round(d, 2) for d in deviations]}")
print("Обратите внимание: сумма отклонений = 0 (проверка корректности)")

# ШАГ 3: Возводим отклонения в квадрат
print("\n" + "-" * 50)
print("ШАГ 3: Возводим отклонения в квадрат (xi - x̄)²")
print("-" * 50)

squared_deviations = [d ** 2 for d in deviations]

print("Квадраты отклонений:")
for i, (dev, sq) in enumerate(zip(deviations, squared_deviations)):
    print(f"  ({dev:.2f})² = {sq:.2f}")

print(f"\nСписок квадратов отклонений: {[round(sq, 2) for sq in squared_deviations]}")

# ШАГ 4: Суммируем квадраты отклонений
print("\n" + "-" * 50)
print("ШАГ 4: Сумма квадратов отклонений (SS - Sum of Squares)")
print("-" * 50)

ss = sum(squared_deviations)

print("Сумма квадратов = ", end="")
for i, sq in enumerate(squared_deviations):
    print(f"{sq:.2f}", end=" + " if i < len(squared_deviations) - 1 else "")
print(f" = {ss:.2f}")

# ШАГ 5: Делим на (n-1) для выборочной дисперсии
print("\n" + "-" * 50)
print("ШАГ 5: Вычисляем выборочную дисперсию s² = SS / (n-1)")
print("-" * 50)

variance_manual = ss / (n - 1)

print(f"Делим на (n-1) = {n} - 1 = {n - 1}")
print(f"Выборочная дисперсия s² = {ss:.2f} / {n - 1} = {variance_manual:.4f}")
print(f"Округлённо: {variance_manual:.2f}")

