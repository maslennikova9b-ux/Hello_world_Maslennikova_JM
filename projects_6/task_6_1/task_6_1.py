import pandas as pd

# Создаём DataFrame с информацией о 10 студентах (с вашими одногруппниками)
data = {
    'name': ['Катя', 'Полина', 'Миша', 'Илья', 'Арсений',
             'Юра', 'Таня', 'Ксюша', 'Соня', 'Си'],
    'gender': ['жен', 'жен', 'муж', 'муж', 'муж',
               'муж', 'жен', 'жен', 'жен', 'муж'],
    'course_grade': ['хорошо', 'отлично', 'хорошо', 'удовлетворительно', 'отлично',
                     'хорошо', 'удовлетворительно', 'отлично', 'хорошо', 'удовлетворительно'],
    'age': [19, 18, 20, 19, 21, 20, 18, 19, 20, 19],
    'exam_score': [85.5, 94.2, 73.8, 67.3, 91.4, 79.1, 88.0, 82.3, 70.0, 64.5]
}

df = pd.DataFrame(data)

print("Исходный DataFrame с одногруппниками:")
print(df)
print("\n" + "="*60 + "\n")

# 2. Выводим типы данных с объяснениями
print("Типы данных столбцов:")
print(df.dtypes)
print("\nОбъяснение типов данных:")
print("• 'name' -> object (строковый): номинальные данные - служат для идентификации студентов")
print("• 'gender' -> object: номинальные данные - категории 'муж'/'жен' без порядка")
print("• 'course_grade' -> object: порядковые данные (будет преобразован)")
print("• 'age' -> int64: количественные дискретные данные - целые годы")
print("• 'exam_score' -> float64: количественные непрерывные данные - дробные баллы")
print("\n" + "="*60 + "\n")

# 3. Для номинальной переменной 'gender' - value_counts()
print("Номинальная переменная 'gender' - распределение частот:")
print(df['gender'].value_counts())
print("\n" + "="*60 + "\n")

# 4. Для порядковой переменной 'course_grade' задаём правильный порядок
grade_order = ['удовлетворительно', 'хорошо', 'отлично']
df['course_grade_ordered'] = pd.Categorical(
    df['course_grade'],
    categories=grade_order,
    ordered=True
)

print("Порядковая переменная 'course_grade' с заданным порядком:")
print("Порядок: удовлетворительно < хорошо < отлично")
print("\nРаспределение (отсортировано по возрастанию):")
print(df['course_grade_ordered'].value_counts().sort_index())
print("\nПроверка упорядоченности (можно сравнивать):")
print("Пример: 'отлично' > 'хорошо'?",
      df.loc[1, 'course_grade_ordered'] > df.loc[0, 'course_grade_ordered'])  # Полина vs Катя
print("\n" + "="*60 + "\n")

# 5. Для количественной переменной 'exam_score' выводим .describe()
print("Количественная переменная 'exam_score' - описательная статистика:")
print(df['exam_score'].describe().round(2))

# Дополнительно для количественной дискретной 'age'
print("\nКоличественная переменная 'age' (дискретная) - описательная статистика:")
print(df['age'].describe().round(2))

# Дополнительно: отсортируем студентов по успеваемости
print("\n" + "="*60 + "\n")
print("Студенты, отсортированные по успеваемости (от худшей к лучшей):")
print(df.sort_values('course_grade_ordered')[['name', 'course_grade']])