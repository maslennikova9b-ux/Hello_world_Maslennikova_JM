import pandas as pd
import numpy as np
import statistics

print("="*70)
print("ЗАДАНИЕ 1: Сравнение среднего и медианы. Влияние выбросов")
print("="*70)

# ============================================
# ЧАСТЬ 1: РУЧНОЙ РАСЧЁТ СРЕДНЕГО И МЕДИАНЫ
# ============================================

print("\n" + "="*70)
print("ЧАСТЬ 1: Ручной расчёт для времени загрузки страниц")
print("="*70)

# Исходные данные
load_times = [0.8, 1.2, 0.9, 1.5, 1.1, 0.7, 1.3, 12.5, 1.0, 0.9]

print("\nИсходный набор данных (время загрузки в секундах):")
print(load_times)

# ---------- РУЧНОЙ РАСЧЁТ СРЕДНЕГО ----------
print("\n" + "-"*50)
print("ШАГ 1: Вычисление СРЕДНЕГО вручную")
print("-"*50)

# Шаг 1: Суммируем все значения
total_sum = sum(load_times)
print(f"1. Суммируем все значения: {' + '.join(str(x) for x in load_times)} = {total_sum}")

# Шаг 2: Считаем количество элементов
n = len(load_times)
print(f"2. Количество элементов: n = {n}")

# Шаг 3: Делим сумму на количество
mean_manual = total_sum / n
print(f"3. Среднее = Сумма / Количество = {total_sum} / {n} = {mean_manual:.2f} секунд")

# ---------- РУЧНОЙ РАСЧЁТ МЕДИАНЫ ----------
print("\n" + "-"*50)
print("ШАГ 2: Вычисление МЕДИАНЫ вручную")
print("-"*50)

# Шаг 1: Сортируем данные
sorted_times = sorted(load_times)
print(f"1. Сортируем данные по возрастанию:")
print(f"   {sorted_times}")

# Шаг 2: Определяем количество элементов
n = len(sorted_times)
print(f"2. Количество элементов: n = {n} (ЧЁТНОЕ)")

# Шаг 3: Для чётного количества находим два средних элемента
mid1_idx = n // 2 - 1  # индекс первого среднего (0-based)
mid2_idx = n // 2       # индекс второго среднего
mid1 = sorted_times[mid1_idx]
mid2 = sorted_times[mid2_idx]

print(f"3. Находим два средних элемента (индексы {mid1_idx} и {mid2_idx}):")
print(f"   Элемент {mid1_idx + 1}: {mid1}")
print(f"   Элемент {mid2_idx + 1}: {mid2}")

# Шаг 4: Вычисляем среднее арифметическое двух средних элементов
median_manual = (mid1 + mid2) / 2
print(f"4. Медиана = ({mid1} + {mid2}) / 2 = {median_manual:.2f} секунд")

# Проверка через pandas
print("\n" + "-"*50)
print("ШАГ 3: Проверка через pandas")
print("-"*50)

df_load = pd.DataFrame({'load_time_sec': load_times})
mean_pandas = df_load['load_time_sec'].mean()
median_pandas = df_load['load_time_sec'].median()

print(f"Среднее (pandas): {mean_pandas:.2f} сек.")
print(f"Медиана (pandas): {median_pandas:.2f} сек.")
print(f"\n✅ Ручные расчёты совпадают с pandas!")
print(f"   Среднее: {mean_manual:.2f} = {mean_pandas:.2f}")
print(f"   Медиана: {median_manual:.2f} = {median_pandas:.2f}")

print("\n" + "="*70)
print("ВЫВОД ПО ЧАСТИ 1:")
print(f"• Среднее = {mean_manual:.2f} сек. (сильно завышено из-за выброса 12.5)")
print(f"• Медиана = {median_manual:.2f} сек. (устойчива к выбросу)")
print(f"• Разница между средним и медианой: {mean_manual - median_manual:.2f} сек.")

# ============================================
# ЧАСТЬ 2: УДАЛЕНИЕ ВЫБРОСА
# ============================================

print("\n" + "="*70)
print("ЧАСТЬ 2: Анализ после удаления выброса (12.5)")
print("="*70)

# Удаляем выброс
cleaned_times = [t for t in load_times if t != 12.5]
print(f"\nОчищенный набор (без выброса 12.5):")
print(cleaned_times)

# Вычисляем новые метрики
mean_cleaned = sum(cleaned_times) / len(cleaned_times)
sorted_cleaned = sorted(cleaned_times)
n_cleaned = len(sorted_cleaned)

# Медиана для очищенного набора (нечётное количество: 9 элементов)
median_cleaned = sorted_cleaned[n_cleaned // 2]  # для нечётного

print("\n" + "-"*50)
print("РЕЗУЛЬТАТЫ ПОСЛЕ УДАЛЕНИЯ ВЫБРОСА:")
print("-"*50)
print(f"Среднее (очищенное): {mean_cleaned:.2f} сек.")
print(f"Медиана (очищенная): {median_cleaned:.2f} сек.")

print("\n" + "-"*50)
print("СРАВНЕНИЕ С ИСХОДНЫМ НАБОРОМ:")
print("-"*50)

print(f"\nСРЕДНЕЕ:")
print(f"  Исходный набор:     {mean_manual:.2f} сек.")
print(f"  Очищенный набор:    {mean_cleaned:.2f} сек.")
print(f"  Изменение:          {mean_cleaned - mean_manual:+.2f} сек. ({(mean_cleaned/mean_manual - 1)*100:+.1f}%)")

print(f"\nМЕДИАНА:")
print(f"  Исходный набор:     {median_manual:.2f} сек.")
print(f"  Очищенный набор:    {median_cleaned:.2f} сек.")
print(f"  Изменение:          {median_cleaned - median_manual:+.2f} сек. ({(median_cleaned/median_manual - 1)*100:+.1f}%)")

print("\n" + "-"*50)
print("ВЫВОД ПО ЧАСТИ 2:")
print("-"*50)
print("✅ Медиана изменилась незначительно (устойчива к выбросам)")
print("⚠️ Среднее изменилось значительно (чувствительно к выбросам)")
print("📊 Медиана лучше отражает типичное время загрузки страниц")

# ============================================
# ЧАСТЬ 3: ДАННЫЕ О РЕСТОРАНЕ (20 строк + выбросы)
# ============================================

print("\n" + "="*70)
print("ЧАСТЬ 3: Анализ времени выполнения заказов в ресторане")
print("="*70)

# Генерируем данные о времени выполнения заказов (в минутах)
np.random.seed(42)

# Нормальное время выполнения: от 15 до 45 минут
normal_times = np.random.normal(loc=30, scale=5, size=18).round(1)
normal_times = normal_times.clip(15, 45)

# Добавляем 2 выброса (аномально долгие заказы)
outliers = [95.0, 120.0]  # 95 минут и 120 минут

# Объединяем данные
order_times = list(normal_times) + outliers

print("\nДанные о времени выполнения заказов (в минутах):")
print(f"Всего заказов: {len(order_times)}")
print(f"Нормальные заказы: 18 шт. (диапазон 15-45 мин)")
print(f"Выбросы: 2 шт. ({outliers[0]} мин, {outliers[1]} мин)")

# Создаём DataFrame
np.random.shuffle(order_times)  # перемешиваем для реалистичности
restaurant_df = pd.DataFrame({
    'order_id': range(1, 21),
    'preparation_time_min': order_times
})

print("\nПервые 10 заказов:")
print(restaurant_df.head(10))
print(f"\n... и последние 5 заказов:")
print(restaurant_df.tail(5))

# Вычисляем статистики
mean_time = restaurant_df['preparation_time_min'].mean()
median_time = restaurant_df['preparation_time_min'].median()
mode_time = statistics.mode(restaurant_df['preparation_time_min'].round(1))  # округляем для поиска моды

# Дополнительная статистика для анализа
q1 = restaurant_df['preparation_time_min'].quantile(0.25)
q3 = restaurant_df['preparation_time_min'].quantile(0.75)
iqr = q3 - q1

print("\n" + "="*50)
print("РЕЗУЛЬТАТЫ АНАЛИЗА:")
print("="*50)

print(f"\n📊 ОСНОВНЫЕ МЕТРИКИ:")
print(f"   Среднее время выполнения:     {mean_time:.1f} минут")
print(f"   Медианное время выполнения:   {median_time:.1f} минут")
print(f"   Мода (наиболее частое время): около {mode_time:.1f} минут")

print(f"\n📈 ДОПОЛНИТЕЛЬНАЯ СТАТИСТИКА:")
print(f"   Минимальное время:   {restaurant_df['preparation_time_min'].min():.1f} мин")
print(f"   Максимальное время:  {restaurant_df['preparation_time_min'].max():.1f} мин")
print(f"   25-й процентиль:     {q1:.1f} мин")
print(f"   75-й процентиль:     {q3:.1f} мин")
print(f"   Межквартильный размах: {iqr:.1f} мин")

print("\n" + "="*50)
print("ОБЪЯСНЕНИЕ РАЗНИЦЫ МЕЖДУ СРЕДНИМ И МЕДИАНОЙ:")
print("="*50)

print(f"""
В данном примере:
• СРЕДНЕЕ ({mean_time:.1f} мин) > МЕДИАНЫ ({median_time:.1f} мин)

ПОЧЕМУ ТАК ПРОИЗОШЛО?

1. БОЛЬШИНСТВО заказов (18 из 20) выполняются за 15-45 минут
   • Типичное время: ~30 минут

2. ДВА заказа-ВЫБРОСА (95 и 120 минут) сильно увеличивают сумму
   • Сумма всех заказов = сумма нормальных + 95 + 120
   • Среднее = Общая сумма / 20 (выбросы "тянут" среднее вверх)

3. МЕДИАНА смотрит на СЕРЕДИНУ упорядоченного ряда
   • При сортировке выбросы оказываются в конце
   • На позициях 10 и 11 (середина) находятся нормальные значения
   • Поэтому медиана игнорирует выбросы

ЧТО ЭТО ЗНАЧИТ ДЛЯ РЕСТОРАНА?

✅ МЕДИАНА ({median_time:.1f} мин) - честный показатель:
   "Обычный заказ выполняется за {median_time:.1f} минут"

⚠️ СРЕДНЕЕ ({mean_time:.1f} мин) - вводит в заблуждение:
   Создаёт ложное впечатление, что все заказы выполняются дольше

💡 РЕКОМЕНДАЦИЯ:
   Для оценки времени выполнения заказов ИСПОЛЬЗОВАТЬ МЕДИАНУ,
   так как она устойчива к редким, но очень долгим заказам.
""")

# Визуализация распределения (текстовая)
print("\n" + "="*50)
print("РАСПРЕДЕЛЕНИЕ ВРЕМЕНИ ВЫПОЛНЕНИЯ ЗАКАЗОВ:")
print("="*50)

# Создаём гистограмму в текстовом виде
bins = [0, 20, 30, 40, 50, 60, 70, 80, 90, 100, 110, 120, 130]
hist, bin_edges = np.histogram(restaurant_df['preparation_time_min'], bins=bins)

print("\nГистограмма распределения:")
for i in range(len(hist)):
    bar = '█' * hist[i]
    print(f"{bin_edges[i]:3.0f}-{bin_edges[i+1]:3.0f} мин: {bar} ({hist[i]} заказов)")

print("\n" + "="*70)
print("ИТОГОВЫЕ ВЫВОДЫ ПО РАБОТЕ:")
print("="*70)

print("""
✅ МЕДИАНА - устойчивая (робастная) мера центральной тенденции
   • Не чувствительна к выбросам
   • Лучше отражает типичное значение в асимметричных распределениях
   • Предпочтительнее среднего при анализе доходов, цен, времени

❌ СРЕДНЕЕ - чувствительно к выбросам
   • Может сильно искажать реальную картину
   • При наличии одного экстремального значения даёт неверное представление
   • Требует симметричного распределения для корректного использования

📌 ПРАКТИЧЕСКИЙ ВЫВОД:
   Всегда смотрите на МЕДИАНУ вместе со СРЕДНИМ!
   Если они сильно различаются - в данных есть выбросы.
   В таком случае медиана - более надёжный показатель.

🎯 ПРИМЕНЕНИЕ В РЕАЛЬНОЙ ЖИЗНИ:
   • Зарплаты и доходы → Медиана
   • Цены на недвижимость → Медиана  
   • Время выполнения задач → Медиана
   • Рост и вес (симметричные) → Среднее
""")

print("="*70)